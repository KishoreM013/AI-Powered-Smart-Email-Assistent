import logging
from datetime import datetime, timedelta, timezone
from fastapi import APIRouter, Depends
from app.auth.jwt import get_current_user_token
from app.database.connection import get_database

logger = logging.getLogger("smart_email_assistant")
router = APIRouter(prefix="/api/admin", tags=["admin"])

@router.get("/users")
async def get_all_users(current_user: dict = Depends(get_current_user_token)):
    db = get_database()
    cursor = db["users"].find({})
    users = await cursor.to_list(100)
    
    # Strip sensitive details
    for u in users:
        if "gmail_credentials" in u:
            del u["gmail_credentials"]
            
    # Mock data fallback
    if not users:
        users = [{
            "_id": "mock_u1",
            "email": "demo.user@gmail.com",
            "name": "Demo Admin",
            "picture": "https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=150&q=80",
            "created_at": datetime.now(timezone.utc) - timedelta(days=5),
            "last_login": datetime.now(timezone.utc)
        }]
    return users

